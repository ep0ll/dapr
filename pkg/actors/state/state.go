var log = logger.NewLogger("dapr.runtime.actors.state")

const (
	metadataPartitionKey = "partitionKey"

	// These capability names are intentionally local until the matching
	// components-contrib API is available in the dependency pinned by Dapr.
	featureTransactionalETags contribstate.Feature = "TRANSACTIONAL_ETAGS"
	featureCreateOnly         contribstate.Feature = "CREATE_ONLY"

	errStateStoreNotConfigured = `actors: state store does not exist or incorrectly configured. Have you set the property '{"name": "actorStateStore", "value": "true"}' in your state store component file?`
)

var ErrTransactionsTooManyOperations = errors.New("the transaction contains more operations than supported by the state store")

type Interface interface {
	// Get retrieves actor state.
	Get(ctx context.Context, req *api.GetStateRequest, lock bool) (*api.StateResponse, error)

	// GetBulk retrieves actor state in bulk.
	GetBulk(ctx context.Context, req *api.GetBulkStateRequest, lock bool) (api.BulkStateResponse, error)

	// TransactionalStateOperation performs a transactional state operation with the actor state store.
	TransactionalStateOperation(ctx context.Context, ignoreHosted bool, req *api.TransactionalRequest, lock bool) error

	// TransactionalStateOperationWithETags returns the ETags generated by the transaction, keyed by actor state key.
	// The state store must support returning ETags from the same atomic transaction.
	TransactionalStateOperationWithETags(ctx context.Context, ignoreHosted bool, req *api.TransactionalRequest, lock bool) (map[string]string, error)
}

type Backend interface {
	contribstate.Store
	contribstate.TransactionalStore
}

// transactionalStoreWithETags is an optional state-store capability. Its
// implementation must return the ETags produced by the same atomic Multi
// operation, keyed by the full state-store key. A follow-up Get is not
// equivalent: another daprd instance can write between Multi and Get.
type transactionalStoreWithETags interface {
	MultiWithETags(ctx context.Context, request *contribstate.TransactionalStateRequest) (map[string]string, error)
}

func asTransactionalETagStore(store Backend) (transactionalStoreWithETags, bool) {
	etagStore, ok := store.(transactionalStoreWithETags)
	return etagStore, ok && featureTransactionalETags.IsPresent(store.Features())
}

func supportsCreateOnly(store Backend) bool {
	return featureCreateOnly.IsPresent(store.Features())
}

type Options struct {
	AppID      string
	CompStore  *compstore.ComponentStore
	Resiliency resiliency.Provider
	Table      table.Interface
	Placement  placement.Interface

	// TODO: @joshvanl Remove in Dapr 1.12 when ActorStateTTL is finalized.
	StateTTLEnabled bool
}

type state struct {
	appID      string
	compStore  *compstore.ComponentStore
	resiliency resiliency.Provider
	table      table.Interface
	placement  placement.Interface

	missingETagLogged                  sync.Map
	unsupportedTransactionalETagLogged sync.Map
	createOnlyIgnoredLogged            sync.Map

	// TODO: @joshvanl Remove in Dapr 1.12 when ActorStateTTL is finalized.
	stateTTLEnabled bool
}

func New(opts Options) Interface {
	return &state{
		appID:           opts.AppID,
		compStore:       opts.CompStore,
		resiliency:      opts.Resiliency,
		table:           opts.Table,
		placement:       opts.Placement,
		stateTTLEnabled: opts.StateTTLEnabled,
	}
}

func (s *state) Get(ctx context.Context, req *api.GetStateRequest, lock bool) (*api.StateResponse, error) {
	if lock {
		var cancel context.CancelCauseFunc
		var err error
		ctx, cancel, err = s.placement.Lock(ctx, req.ActorType)
		if err != nil {
			return nil, err
		}
		defer cancel(nil)
	}

	storeName, store, err := s.stateStore()
	if err != nil {
		return nil, err
	}

	actorKey := req.ActorKey()
	partitionKey := key.ConstructComposite(s.appID, actorKey)
	metadata := map[string]string{metadataPartitionKey: partitionKey}

	key := s.constructActorStateKey(actorKey, req.Key)

	policyRunner := resiliency.NewRunner[*contribstate.GetResponse](ctx,
		s.resiliency.ComponentOutboundPolicy(storeName, resiliency.Statestore),
	)
	storeReq := &contribstate.GetRequest{
		Key:      key,
		Metadata: metadata,
	}

	resp, err := policyRunner(func(ctx context.Context) (*contribstate.GetResponse, error) {
		return store.Get(ctx, storeReq)
	})
	if err != nil {
		return nil, err
	}

	if resp == nil {
		return &api.StateResponse{}, nil
	}
	etag := resp.ETag
	if req.StrictETag {
		etag = nil
		_, hasAtomicETags := asTransactionalETagStore(store)
		if hasAtomicETags {
			if resp.ETag != nil && *resp.ETag != "" {
				etag = resp.ETag
			} else if resp.Data != nil {
				s.logMissingETag(storeName, req.ActorType, "read")
			}
		} else {
			s.logUnsupportedTransactionalETags(storeName, req.ActorType)
		}
	}

	return &api.StateResponse{
		Data:     resp.Data,
		Metadata: resp.Metadata,
		ETag:     etag,
	}, nil
}

func (s *state) logMissingETag(storeName, actorType, op string) {
	if _, logged := s.missingETagLogged.LoadOrStore(op+"/"+storeName+"/"+actorType, struct{}{}); !logged {
		log.Errorf("Actor state store '%s' advertises %s but returned no ETag on a %s for actor type '%s'. The state is returned without an ETag, so the next save of that key is not guarded. Logged once per actor type", storeName, featureTransactionalETags, op, actorType)
	}
}

func (s *state) logUnsupportedTransactionalETags(storeName, actorType string) {
	if _, logged := s.unsupportedTransactionalETagLogged.LoadOrStore(storeName+"/"+actorType, struct{}{}); !logged {
		log.Warnf("Actor state ETag protection is disabled for actor type '%s': state store '%s' does not advertise or implement atomic transactional ETag support. Actor state reads will not return ETags and writes with an ETag will be rejected", actorType, storeName)
	}
}

func (s *state) logIgnoredCreateOnly(storeName, actorType string) {
	if _, logged := s.createOnlyIgnoredLogged.LoadOrStore(storeName+"/"+actorType, struct{}{}); !logged {
		log.Warnf("Actor state create-only protection is disabled for actor type '%s': state store '%s' does not advertise create-only support. createOnly operations will use last-write-wins semantics", actorType, storeName)
	}
}

func (s *state) GetBulk(ctx context.Context, req *api.GetBulkStateRequest, lock bool) (api.BulkStateResponse, error) {
	if lock {
		var cancel context.CancelCauseFunc
		var err error
		ctx, cancel, err = s.placement.Lock(ctx, req.ActorType)
		if err != nil {
			return nil, err
		}
		defer cancel(nil)
	}

	storeName, store, err := s.stateStore()
	if err != nil {
		return nil, err
	}

	actorKey := req.ActorKey()
	baseKey := key.ConstructComposite(s.appID, actorKey)
	metadata := map[string]string{metadataPartitionKey: baseKey}

	bulkReqs := make([]contribstate.GetRequest, len(req.Keys))
	for i, key := range req.Keys {
		bulkReqs[i] = contribstate.GetRequest{
			Key:      s.constructActorStateKey(actorKey, key),
			Metadata: metadata,
		}
	}

	policyRunner := resiliency.NewRunner[[]contribstate.BulkGetResponse](ctx,
		s.resiliency.ComponentOutboundPolicy(storeName, resiliency.Statestore),
	)
	res, err := policyRunner(func(ctx context.Context) ([]contribstate.BulkGetResponse, error) {
		return store.BulkGet(ctx, bulkReqs, contribstate.BulkGetOpts{})
	})
	if err != nil {
		return nil, err
	}

	// Add the dapr separator to baseKey
	baseKey += api.DaprSeparator

	bulkRes := make(api.BulkStateResponse, len(res))
	for _, r := range res {
		if r.Error != "" {
			return nil, fmt.Errorf("failed to retrieve key '%s': %s", r.Key, r.Error)
		}

		// Trim the prefix from the key
		bulkRes[strings.TrimPrefix(r.Key, baseKey)] = api.BulkStateEntry{
			Data: r.Data,
			ETag: r.ETag,
		}
	}

	return bulkRes, nil
}

func (s *state) TransactionalStateOperation(ctx context.Context, ignoreHosted bool, req *api.TransactionalRequest, lock bool) error {
	_, err := s.transactionalStateOperation(ctx, ignoreHosted, req, lock, false)
	return err
}

func (s *state) TransactionalStateOperationWithETags(ctx context.Context, ignoreHosted bool, req *api.TransactionalRequest, lock bool) (map[string]string, error) {
	return s.transactionalStateOperation(ctx, ignoreHosted, req, lock, true)
}

func (s *state) transactionalStateOperation(ctx context.Context, ignoreHosted bool, req *api.TransactionalRequest, lock bool, returnETags bool) (map[string]string, error) {
	if lock {
		var cancel context.CancelCauseFunc
		var err error
		ctx, cancel, err = s.placement.Lock(ctx, req.ActorType)
		if err != nil {
			return nil, err
		}
		defer cancel(nil)
	}

	if !ignoreHosted && !s.table.ActorExists(req.ActorType, req.ActorID) {
		return nil, messages.ErrActorInstanceMissing
	}

	operations := make([]contribstate.TransactionalStateOperation, len(req.Operations))
	baseKey := key.ConstructComposite(s.appID, req.ActorKey())
	metadata := map[string]string{metadataPartitionKey: baseKey}
	baseKey += api.DaprSeparator
	var err error
	for i, o := range req.Operations {
		operations[i], err = o.StateOperation(baseKey, api.StateOperationOpts{
			Metadata: metadata,
			// TODO: @joshvanl Remove in Dapr 1.12 when ActorStateTTL is finalized.
			StateTTLEnabled: s.stateTTLEnabled,
			FirstWriteETag:  req.FirstWriteETag,
		})
		if err != nil {
			if req.FirstWriteETag {
				return nil, toETagAPIError(err)
			}
			return nil, err
		}
	}

	etags, err := s.executeStateStoreTransaction(ctx, req.ActorType, operations, metadata, baseKey, req.FirstWriteETag, returnETags)
	if req.FirstWriteETag {
		err = toETagAPIError(err)
	}
	return etags, err
}

func toETagAPIError(err error) error {
	var etagErr *contribstate.ETagError
	if errors.As(err, &etagErr) {
		switch etagErr.Kind() {
		case contribstate.ETagMismatch:
			return messages.ErrActorStateETagMismatch.WithFormat(err)
		case contribstate.ETagInvalid:
			return messages.ErrActorStateETagInvalid.WithFormat(err)
		}
	}
	return err
}

func (s *state) executeStateStoreTransaction(
	ctx context.Context,
	actorType string,
	operations []contribstate.TransactionalStateOperation,
	metadata map[string]string,
	baseKey string,
	public bool,
	returnETags bool,
) (map[string]string, error) {
	storeName, store, err := s.stateStore()
	if err != nil {
		return nil, err
	}

	if maxMulti, ok := store.(contribstate.TransactionalStoreMultiMaxSize); ok {
		max := maxMulti.MultiMaxSize()
		if max > 0 && len(operations) > max {
			return nil, ErrTransactionsTooManyOperations
		}
	}

	stateReq := &contribstate.TransactionalStateRequest{
		Operations: operations,
		Metadata:   metadata,
	}

	// Determine the final operation for each key before executing the
	// transaction. Only keys whose final operation is an upsert need an ETag
	// in the response.
	finalOps := make(map[string]bool, len(operations))
	requiresETagSupport := false
	for _, op := range operations {
		switch o := op.(type) {
		case contribstate.SetRequest:
			if !strings.HasPrefix(o.Key, baseKey) {
				return nil, fmt.Errorf("actor state transaction key %q does not have the expected prefix", o.Key)
			}
			finalOps[strings.TrimPrefix(o.Key, baseKey)] = true
			requiresETagSupport = requiresETagSupport || (public && o.HasETag())
		case contribstate.DeleteRequest:
			if !strings.HasPrefix(o.Key, baseKey) {
				return nil, fmt.Errorf("actor state transaction key %q does not have the expected prefix", o.Key)
			}
			finalOps[strings.TrimPrefix(o.Key, baseKey)] = false
			requiresETagSupport = requiresETagSupport || (public && o.HasETag())
		}
	}

	requiresReturnedETags := false
	if returnETags {
		for _, upsert := range finalOps {
			requiresReturnedETags = requiresReturnedETags || upsert
		}
	}

	storeWithETags, hasTransactionalETags := asTransactionalETagStore(store)
	if requiresETagSupport && !hasTransactionalETags {
		// FeatureETag and FeatureTransactional alone do not guarantee that
		// conditional writes are checked atomically across Multi. Never send a
		// conditional actor transaction to a store without that contract.
		s.logUnsupportedTransactionalETags(storeName, actorType)
		return nil, messages.ErrActorStateETagUnsupported.WithFormat(storeName)
	}

	storeSupportsCreateOnly := supportsCreateOnly(store)
	if public && !storeSupportsCreateOnly {
		for i, op := range operations {
			setReq, ok := op.(contribstate.SetRequest)
			if !ok || setReq.Options.Concurrency != contribstate.FirstWrite || setReq.HasETag() {
				continue
			}

			// Older stores may not distinguish create-only from an ordinary
			// upsert. Keep their historical last-write-wins behavior rather
			// than making first saves from upgraded SDKs fail.
			setReq.Options.Concurrency = contribstate.LastWrite
			operations[i] = setReq
			s.logIgnoredCreateOnly(storeName, actorType)
		}
	}

	useMultiWithETags := hasTransactionalETags &&
		(requiresETagSupport || (returnETags && requiresReturnedETags))
	policyRunner := resiliency.NewRunner[map[string]string](ctx,
		s.resiliency.ComponentOutboundPolicy(storeName, resiliency.Statestore),
	)
	etags, err := policyRunner(func(ctx context.Context) (map[string]string, error) {
		var (
			result   map[string]string
			multiErr error
		)
		if useMultiWithETags {
			result, multiErr = storeWithETags.MultiWithETags(ctx, stateReq)
		} else {
			multiErr = store.Multi(ctx, stateReq)
		}

		var etagErr *contribstate.ETagError
		if errors.As(multiErr, &etagErr) {
			// Replaying the same transaction with the same ETag cannot resolve
			// a mismatch. Return it immediately so the caller can reload state
			// and make a fresh decision instead of retrying under the actor lock.
			return nil, backoff.Permanent(multiErr)
		}
		return result, multiErr
	})
	if err != nil {
		return nil, err
	}

	if !returnETags {
		return nil, nil
	}
	if !useMultiWithETags {
		// The state store is not strict. The transaction has still committed,
		// but there are no new ETags for the caller to cache.
		return map[string]string{}, nil
	}
	if etags == nil {
		etags = make(map[string]string)
	}

	// Convert the full state-store keys returned by MultiWithETags to the
	// actor-relative keys exposed by the public API. Do not synthesize ETags
	// with a subsequent Get, as that can return a different transaction's
	// value and make a stale actor write appear current.
	actorETags := make(map[string]string, len(etags))
	for storeKey, etag := range etags {
		if !strings.HasPrefix(storeKey, baseKey) {
			log.Errorf("State store '%s' returned an ETag for a key outside actor type '%s'", storeName, actorType)
			continue
		}
		if etag == "" {
			continue
		}
		actorETags[strings.TrimPrefix(storeKey, baseKey)] = etag
	}

	// Log omissions but don't return an error after the transaction has
	// committed: the caller must not retry a transaction that already wrote.
	for key, upsert := range finalOps {
		if upsert {
			if _, ok := actorETags[key]; !ok {
				log.Errorf("State store '%s' did not return an ETag for an upserted key of actor type '%s' after a successful transaction", storeName, actorType)
			}
		}
	}

	return actorETags, nil
}

// stateStore resolves the actor state store from the component store on
// every call, so the store can be hot reloaded (added, replaced, or removed)
// at any point in the runtime's lifetime.
func (s *state) stateStore() (string, Backend, error) {
	storeS, storeName, ok := s.compStore.GetStateStoreActor()
	if !ok {
		return "", nil, messages.ErrActorRuntimeNotFound
	}

	store, ok := storeS.(Backend)
	if !ok || !contribstate.FeatureETag.IsPresent(store.Features()) || !contribstate.FeatureTransactional.IsPresent(store.Features()) {
		return "", nil, errors.New(errStateStoreNotConfigured)
	}

	return storeName, store, nil
}

func (s *state) constructActorStateKey(actorKey, actorID string) string {
	return key.ConstructComposite(s.appID, actorKey, actorID)
}
